// Game scenes use a portrait layer above scenery. The renderer resamples these
// cell maps instead of stamping isolated points, keeping outlines connected at
// both phone and desktop resolutions. Small appendages animate independently.
export function drawCharacterCells(art, kind, scene) {
  const rows = drawings[kind];
  if (!rows) return false;
  const colors = {
    ...palette,
    // A brief blink changes only the eyes, never stretches the face.
    b: [palette.b[0], art.time % 5 > 4.82 ? "-" : "O"],
    ...(["shadow", "no-face"].includes(kind)
      ? { K: [[99, 91, 137], "@"] }
      : {}),
  };
  art.stamp(rows, colors, { baseline: 13 });
  if (kind === "sora" || kind === "roxas") {
    // A bright keychain charm swings from the handle, not the whole body.
    const phase = Math.sin(art.time * 2) * 1.3;
    art.stroke(8, 11, 8 + phase, 14, [245, 215, 120], ":");
    art.at(8 + phase, 14, "o", [255, 232, 171]);
  }
  if (scene.food.length && ["link", "toon-link"].includes(kind)) {
    for (let i = 0; i < 3; i++) {
      art.at(
        11 + Math.sin(art.time * 3 + i) * 2,
        -12 + i * 2,
        "*",
        [241, 244, 177],
      );
    }
  }
  return true;
}
